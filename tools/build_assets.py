#!/usr/bin/env python3
"""Pack the static assets into src/kernel/00_assets.js.

Inputs (all under src/assets/):
  resicons/*.svg      Resi icons, 20x20, filled paths. Fill becomes currentColor.
  bricky32.png        Bricky, 32x32 pixel art (from Labs OS 3.1).
  bricky32Blink.png   Bricky, blinking.
  labs-os-3.1.html    The previous Labs OS build, run by the Brine app.

Run after changing any asset. The output is committed, so a normal build does not need this.
"""
import base64
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / "src" / "assets"
OUT = ROOT / "src" / "kernel" / "00_assets.js"


def round_numbers(path_data: str) -> str:
    def fix(m):
        n = float(m.group(0))
        s = f"{n:.2f}".rstrip("0").rstrip(".")
        return "0" if s in ("-0", "") else s
    return re.sub(r"-?\d+\.\d+", fix, path_data)


def icon(svg_text: str) -> str:
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg_text, re.S).group(1)
    inner = re.sub(r'fill="#[0-9A-Fa-f]{3,6}"', 'fill="currentColor"', inner)
    inner = re.sub(r'd="([^"]+)"', lambda m: 'd="' + round_numbers(m.group(1)) + '"', inner)
    inner = re.sub(r"\s+", " ", inner).strip()
    return f'<svg viewBox="0 0 20 20" fill="none" xmlns="http://www.w3.org/2000/svg">{inner}</svg>'


def data_url(p: pathlib.Path, mime: str) -> str:
    return f"data:{mime};base64," + base64.b64encode(p.read_bytes()).decode()


def main():
    icons = {p.stem: icon(p.read_text()) for p in sorted((ASSETS / "resicons").glob("*.svg"))}
    legacy = base64.b64encode((ASSETS / "labs-os-3.1.html").read_bytes()).decode()
    body = {
        "icons": icons,
        "bricky": data_url(ASSETS / "bricky32.png", "image/png"),
        "brickyBlink": data_url(ASSETS / "bricky32Blink.png", "image/png"),
        "legacy": legacy,
    }
    OUT.write_text(
        "// Generated by tools/build_assets.py. Do not edit by hand.\n"
        "const OS_ASSETS = " + json.dumps(body, separators=(",", ":")) + ";\n"
    )
    print(f"{OUT.relative_to(ROOT)}: {len(icons)} icons, {OUT.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
